const INDUSTRY_FALLBACK = 'Total Market';

function industryFor(yahooIndustry) {
  const name = (yahooIndustry && YAHOO_TO_DAMODARAN[yahooIndustry]) || null;
  const row = name ? DAMODARAN_INDUSTRIES[name] : null;
  if (row) return { name, unleveredBeta: row.unleveredBeta, salesToCapital: row.salesToCapital, mapped: true };
  const fb = DAMODARAN_INDUSTRIES[INDUSTRY_FALLBACK] || { unleveredBeta: null, salesToCapital: null };
  return { name: INDUSTRY_FALLBACK, unleveredBeta: fb.unleveredBeta, salesToCapital: fb.salesToCapital, mapped: false };
}

